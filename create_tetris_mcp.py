# 构建创建文档的请求体
create_doc_payload = {
    "jsonrpc": "2.0",
    "id": 1,
    "method": "tools/call",
    "params": {
        "name": "create-doc",
        "arguments": {
            "title": "俄罗斯方块游戏需求文档",
            "markdown": markdown_content
        }
    }
}

print("正在使用飞书MCP创建俄罗斯方块游戏需求文档...")
print(f"请求URL: {mcp_url}")
print(f"请求头: {headers}")

# 发送请求
response = requests.post(mcp_url, headers=headers, json=create_doc_payload)

print(f"\n响应状态码: {response.status_code}")
print(f"响应内容: {response.text}")

try:
    result = response.json()
    print(f"\nJSON解析结果: {json.dumps(result, indent=2, ensure_ascii=False)}")
    
    # 提取文档信息
    if result.get("result") and result["result"].get("content"):
        content = result["result"]["content"][0]["text"]
        content_json = json.loads(content)
        print(f"\n文档创建成功！")
        print(f"文档ID: {content_json.get('doc_id')}")
        print(f"文档URL: {content_json.get('doc_url')}")
except json.JSONDecodeError as e:
    print(f"JSON解析失败: {e}")
except Exception as e:
    print(f"处理响应失败: {e}")
