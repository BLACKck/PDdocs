print("正在恢复俄罗斯方块游戏需求文档...")
print(f"文档 ID: {doc_id}")

# 构建更新文档的请求体
payload = {
    "jsonrpc": "2.0",
    "id": 1,
    "method": "tools/call",
    "params": {
        "name": "update-doc",
        "arguments": {
            "doc_id": doc_id,
            "mode": "overwrite",
            "markdown": updated_markdown
        }
    }
}

# 发送更新文档请求
response = requests.post(mcp_url, headers=headers, json=payload)

print(f"\n响应状态码：{response.status_code}")
print(f"响应内容：{response.text}")

try:
    result = response.json()
    if result.get("result") and result["result"].get("content"):
        content = result["result"]["content"][0]["text"]
        content_json = json.loads(content)
        if content_json.get("success"):
            print(f"\n文档恢复成功！")
            print(f"文档 ID: {content_json.get('doc_id')}")
            print(f"文档 URL: https://www.feishu.cn/docx/{doc_id}")
        else:
            print(f"\n文档恢复失败")
            print(f"错误信息：{content_json.get('error', '未知错误')}")
    else:
        print("\n文档恢复失败")
except json.JSONDecodeError as e:
    print(f"JSON 解析失败：{e}")
except Exception as e:
    print(f"处理响应失败：{e}")
