# 构建MCP请求
payload = {
    "toolcalls": [
        {
            "thought": "创建俄罗斯方块游戏需求文档",
            "name": "create-doc",
            "params": {
                "title": "俄罗斯方块游戏需求文档",
                "content": doc_content,
                "folder_token": ""
            }
        }
    ]
}

# 发送请求
try:
    response = requests.post(mcp_url, json=payload, headers={"Authorization": auth_header})
    print(f"响应状态码: {response.status_code}")
    print(f"响应内容: {response.text}")
    
    try:
        result = response.json()
        print(f"JSON解析结果: {json.dumps(result, indent=2, ensure_ascii=False)}")
        
        if result.get("ok"):
            print("文档创建成功！")
            print(f"文档链接: {result.get('data', {}).get('document_url')}")
        else:
            print("文档创建失败：")
            print(result.get("error", {}).get("message", "未知错误"))
    except json.JSONDecodeError as e:
        print(f"JSON解析失败: {e}")
        print("响应内容不是有效的JSON格式")
except Exception as e:
    print(f"请求失败: {e}")
